let lang = 'en';
export function setLang(l) { lang = S[l] ? l : 'en'; }
export function getLang() { return lang; }
export function locale() { return (LANGS.find((x) => x.id === lang) || LANGS[0]).locale; }
export function t(key, vars = {}) {
  const s = (S[lang] && S[lang][key] !== undefined ? S[lang][key] : S.en[key]) ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}
// Fill every element marked data-i18n (text) or data-i18n-html (markup) or data-i18n-aria.
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) {
    const v = t(el.dataset.i18nHtml);
    el.innerHTML = v;
    el.hidden = !v;
  }
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.dataset.i18nTitle));
}
